async def generate_one(movement, feedback, text):
    mp3_path = os.path.join(OUT_DIR, f"combo_{movement}_{feedback}.mp3")
    wav_path = os.path.join(OUT_DIR, f"combo_{movement}_{feedback}.wav")

    communicate = edge_tts.Communicate(text, VOICE)
    await communicate.save(mp3_path)

    subprocess.run(["ffmpeg", "-y", "-i", mp3_path, wav_path], check=True, capture_output=True)
    os.remove(mp3_path)
    print(f"combo_{movement}_{feedback}.wav נוצר")

async def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for (movement, feedback), text in COMBOS.items():
        await generate_one(movement, feedback, text)
    print(f"סיימתי - כל {len(COMBOS)} קבצי המלצות המשולבות מוכנים ב-speaker_audio/")

if __name__ == "__main__":
    asyncio.run(main())
